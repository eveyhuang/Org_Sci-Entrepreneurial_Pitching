"""Exploratory whole-pitch-held-out concept ranking; no annotation API calls.

Rank numerical concept values with all availability flags held fixed. Positive
leave-one-concept-out gains mean retaining the concept reduces log loss. Bootstrap
intervals resample pitches from fixed held-out predictions, not model refits.
"""
from pathlib import Path
import argparse
import sys
import pandas as pd
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT))


from analysis.concept_ranking import rank_concepts


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--run-name',default='stage_b_sample50');args=ap.parse_args()
    base=ROOT/'runs'/args.run_name/'analysis/project_v2'
    d=pd.read_csv(base/'decision_cohort.csv')
    out=base/'concept_ranking';out.mkdir(exist_ok=True)
    for name,cohort in [('all',d),('unflagged',d[~d.has_flags])]:
        r,m,p=rank_concepts(cohort)
        r.to_csv(out/f'{name}_ranking.csv',index=False)
        m.to_csv(out/f'{name}_metrics.csv',index=False)
        p.to_csv(out/f'{name}_predictions.csv',index=False)
        print(name);print(r.round(5).to_string(index=False))
        print(m[m.model.isin(['offer_rate','availability_baseline','full'])].round(5).to_string(index=False))
    (out/'README.md').write_text('''# Exploratory concept ranking

Generated by `scripts/analysis/rank_bottleneck_concepts.py` from the saved v2
`decision_cohort.csv`. Four named concepts only; availability flags are held
constant across full, ablated, and single-concept models. The fixed ridge penalty
is 1, preprocessing is training-only, and entire pitches are held out.

Incremental gain = held-out log loss without the concept minus full-model log loss.
Standalone gain = availability-only log loss minus single-concept-plus-availability
log loss. Positive means the concept improves prediction. These measure predictive
utility of concept values conditional on availability, not causal influence,
coefficient size, or construct validity. "Alone" still includes all availability
flags so missingness cannot masquerade as value information.

95% intervals use 1,999 paired pitch bootstrap draws of fixed held-out predictions
(seed 20260928), not model refits. They are pointwise, not adjusted for four
comparisons or post-hoc ranking. Do not use this exploratory ranking to select a
model and report its performance as independent validation. The unflagged cohort
is a sensitivity analysis that changes the sample.
''')

if __name__=='__main__':main()
